func render(t *testing.T, c templ.Component) string {
	t.Helper()
	var buf bytes.Buffer
	if err := c.Render(context.Background(), &buf); err != nil {
		t.Fatalf("Render: %v", err)
	}
	return buf.String()
}

func TestJoin_OrderAndNil(t *testing.T) {
	got := render(t, compose.Join(nil, compose.Text("a"), nil, compose.Text("b"), compose.Text("c"), nil))
	if got != "abc" {
		t.Fatalf("got %q, want %q", got, "abc")
	}
	if got := render(t, compose.Join()); got != "" {
		t.Fatalf("empty Join rendered %q", got)
	}
}

func TestJoin_StopsAtError(t *testing.T) {
	boom := errors.New("boom")
	failing := templ.ComponentFunc(func(context.Context, io.Writer) error { return boom })
	var buf bytes.Buffer
	err := compose.Join(compose.Text("a"), failing, compose.Text("b")).Render(context.Background(), &buf)
	if !errors.Is(err, boom) || buf.String() != "a" {
		t.Fatalf("got %q, %v; want %q, %v", buf.String(), err, "a", boom)
	}
}

func TestText_Escapes(t *testing.T) {
	got := render(t, compose.Text(`<script>alert("x")</script> & 'y'`))
	if strings.ContainsAny(got, "<>") {
		t.Fatalf("Text rendered markup: %q", got)
	}
	if !strings.Contains(got, "&lt;script&gt;") || !strings.Contains(got, "&amp;") {
		t.Fatalf("Text did not escape: %q", got)
	}
}

func TestWith_NilParent(t *testing.T) {
	err := compose.With(nil, compose.Text("x")).Render(context.Background(), io.Discard)
	if err == nil {
		t.Fatal("With(nil, ...) rendered without error")
	}
}

// A badge inside a card shows only its own text, the card's other children
// come once each, in order, and nothing follows the card's closing tag.
func TestWith_NestedContainers(t *testing.T) {
	got := render(t, compose.With(card.Card(),
		compose.Text("before"),
		compose.With(badge.Badge(), compose.Text("New")),
		compose.Text("after"),
	))
	b := render(t, compose.With(badge.Badge(), compose.Text("New")))
	if !strings.Contains(got, b) {
		t.Fatalf("card does not contain the badge exactly as rendered alone:\nbadge: %s\ncard:  %s", b, got)
	}
	for _, s := range []string{"before", "New", "after"} {
		if n := strings.Count(got, s); n != 1 {
			t.Fatalf("%q appears %d times, want 1:\n%s", s, n, got)
		}
	}
	if !(strings.Index(got, "before") < strings.Index(got, b) && strings.Index(got, b) < strings.Index(got, "after")) {
		t.Fatalf("children out of order:\n%s", got)
	}
	if !strings.HasSuffix(got, "after</div>") {
		t.Fatalf("content after the card's closing tag:\n%s", got)
	}
}

// detailpage.Page passes its children two templates deep (Page > body);
// a card given as one of them still shows only its own children.
func TestWith_DeepContainer(t *testing.T) {
	got := render(t, compose.With(detailpage.Page(detailpage.Props{}),
		compose.With(card.Card(), compose.Text("inner")),
		compose.Text("outer"),
	))
	if strings.Count(got, "inner") != 1 || strings.Count(got, "outer") != 1 {
		t.Fatalf("children repeated or lost:\n%s", got)
	}
	if strings.Index(got, "inner") > strings.Index(got, "outer") {
		t.Fatalf("children out of order:\n%s", got)
	}
}

// Dropdown hands its content ID to Trigger and Content through the render
// context; children given with With must render under that context.
func TestWith_ChildrenSeeParentContext(t *testing.T) {
	got := render(t, compose.With(dropdown.Dropdown(dropdown.Props{ID: "menu-x"}),
		compose.With(dropdown.Trigger(), compose.Text("Open")),
		compose.With(dropdown.Content(), compose.With(dropdown.Item(), compose.Text("Edit"))),
	))
	if n := strings.Count(got, "menu-x"); n < 2 {
		t.Fatalf("content ID appears %d times, want Trigger and Content both to use it:\n%s", n, got)
	}
}

// A parent not generated by templ that renders the children it was given
// without taking them off the context (as a hand-written wrapper might).
var passThrough = templ.ComponentFunc(func(ctx context.Context, w io.Writer) error {
	return templ.GetChildren(ctx).Render(ctx, w)
})

// A child container must not take the parent's children as its own, even
// when the parent leaves them on the context. probe is given no children
// and reads them as a generated container does; if it got the parent's, it
// would render itself again, so it fails on its second render (a badge in
// its place would recurse until the stack overflows).
func TestWith_ChildDoesNotInheritParentChildren(t *testing.T) {
	renders := 0
	probe := templ.ComponentFunc(func(ctx context.Context, w io.Writer) error {
		renders++
		if renders > 1 {
			return errors.New("a child rendered the parent's children again")
		}
		return templ.GetChildren(ctx).Render(templ.ClearChildren(ctx), w)
	})
	got := render(t, compose.With(passThrough, compose.Text("own "), probe))
	if got != "own " {
		t.Fatalf("got %q, want %q", got, "own ")
	}
}

// A parent that never reads its children must not leave them behind for
// the next container rendered with the same context. The pair sits inside
// a card because templ shares the children record only within a render that
// a generated component has started.
func TestWith_NoLeftoverChildren(t *testing.T) {
	ignores := compose.Join(compose.Text("plain"))
	got := render(t, compose.With(card.Card(),
		compose.With(ignores, compose.Text("LEFTOVER")),
		badge.Badge(),
	))
	if strings.Contains(got, "LEFTOVER") {
		t.Fatalf("a later badge rendered children it was never given:\n%s", got)
	}
}
