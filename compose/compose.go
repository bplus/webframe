// Package compose builds component trees in plain Go, without a .templ file.
//
// A container component (card.Card, layout.Stack, badge.Badge, ...) renders
// its content where its template says { children... }. In templ syntax that
// content is the block after the call; in Go it is passed with With:
//
//	compose.With(card.Card(),
//		compose.With(badge.Badge(), compose.Text("New")),
//		compose.Text("Ready to ship."),
//	)
//
// Join renders components one after another, and Text renders a string as
// escaped text. None of the three ever emits markup of its own.
package compose

import (
	"context"
	"errors"
	"io"

	"github.com/a-h/templ"
)

// With returns parent rendered with children, in order, as its
// { children... }. Nil children are skipped.
//
// templ keeps the children on one record shared by the whole render, and a
// component generated by templ takes its children off that record before
// it renders anything. With does the same for components that were not
// generated by templ: the children are rendered with the record cleared,
// so a container among them never takes the parent's children as its own,
// and the record is cleared again once parent has rendered, so a parent
// that never reads its children (one built with Join, for example) does not
// leave them behind for the next container rendered with the same context.
func With(parent templ.Component, children ...templ.Component) templ.Component {
	joined := Join(children...)
	inner := templ.ComponentFunc(func(ctx context.Context, w io.Writer) error {
		return joined.Render(templ.ClearChildren(ctx), w)
	})
	return templ.ComponentFunc(func(ctx context.Context, w io.Writer) error {
		if parent == nil {
			return errors.New("compose.With: parent is nil")
		}
		ctx = templ.WithChildren(ctx, inner)
		err := parent.Render(ctx, w)
		templ.ClearChildren(ctx)
		return err
	})
}

// Join returns a component that renders cs in order. Nil entries are
// skipped. The first error stops the render and is returned.
func Join(cs ...templ.Component) templ.Component {
	return templ.ComponentFunc(func(ctx context.Context, w io.Writer) error {
		for _, c := range cs {
			if c == nil {
				continue
			}
			if err := c.Render(ctx, w); err != nil {
				return err
			}
		}
		return nil
	})
}

// Text returns a component that renders s as escaped text. It never
// renders s as HTML: "<b>" comes out as the four characters <b>.
func Text(s string) templ.Component {
	return templ.ComponentFunc(func(_ context.Context, w io.Writer) error {
		_, err := io.WriteString(w, templ.EscapeString(s))
		return err
	})
}
